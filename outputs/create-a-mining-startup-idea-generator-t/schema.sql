CREATE TABLE Users (
    UserId INT PRIMARY KEY AUTO_INCREMENT,
    Name VARCHAR(100) NOT NULL,
    Email VARCHAR(100) UNIQUE NOT NULL,
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UpdatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE MiningSites (
    SiteId INT PRIMARY KEY AUTO_INCREMENT,
    Location VARCHAR(255) NOT NULL,
    MineralType VARCHAR(100),
    DepositSize DECIMAL(18, 2),
    EstimatedProductionCapacity DECIMAL(18, 2),
    ExplorationStatus ENUM('Exploring', 'Discovered', 'Developed') DEFAULT 'Exploring',
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UpdatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE StartupIdeas (
    IdeaId INT PRIMARY KEY AUTO_INCREMENT,
    Title VARCHAR(255) NOT NULL,
    Description TEXT NOT NULL,
    RelatedMineralType VARCHAR(100),
    FeasibilityScore INT CHECK (FeasibilityScore BETWEEN 0 AND 100),
    EstimatedCost DECIMAL(18, 2),
    LinkedMiningSiteId INT,
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UpdatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (LinkedMiningSiteId) REFERENCES MiningSites(SiteId)
);

CREATE TABLE UserFavorites (
    FavoriteId INT PRIMARY KEY AUTO_INCREMENT,
    UserId INT,
    IdeaId INT UNIQUE,
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (UserId) REFERENCES Users(UserId),
    FOREIGN KEY (IdeaId) REFERENCES StartupIdeas(IdeaId)
);